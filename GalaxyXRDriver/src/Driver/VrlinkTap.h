// ============================================================================
// VrlinkTap — in-process publisher of the async-spacewarp enable/mode value to
// the Steam Link VR stream (brief 11-W2B-HOST-VRLINKTAP, add-feature 2026-10-17;
// mode carrier brief C, 2026-10-20).
//
// Runtime target: Valve's driver_vrlink.dll, already loaded in vrserver beside
// this driver. NO hooks on Valve code except ONE lifecycle hook: the typed
// ValueTransportSystem::UpdateValue public thunk (tail target: its worker).
// The locator is a validated signature scan, not a build hash or fixed RVA:
// see VrlinkSignature.h and "Derivation + gate" below. The hook is
// capture+passthrough: vrlink's own publishes run byte-identically through the
// MinHook trampoline, and each one teaches the tap the live value-transport
// `this` pointer. The tap then publishes one extra 4-byte value on UNUSED
// ValueTransportID 0x48 through that same thunk, using exactly the call shape
// of vrlink's live-proven VTE_USE_ENCODE_TARGET_WIDTH (id 11) width publishes;
// the receiving VR client auto-instantiates unknown value ids (06-bridge §3).
//
// Carrier encoding (2026-10-20): ONE u32 on 0x48 carries the whole state, so the
// Companion needs no second id and no new RE. Carrier values: 0 = off,
// 1 = late frames only, 2 = half rate. The stored setting is
// streamFrame.spacewarpMode (0 = late frames only, the default; 1 = half rate;
// any other stored value is treated as the default). The carrier value is
// derived from the CURRENT stored (enabled, mode) pair on every publish
// attempt, never from a captured request:
//   want = enabled ? (mode == 1 ? 2u : 1u) : 0u
// so a client that only understands the legacy boolean still reads 1 and 2 as
// "enabled", and an explicit Off publishes 0 (only when a value was actually
// delivered). 2026-10-21 (owner directive): half rate is retired, so
// EncodeCarrierValue also gates on kHalfRateRetired and publishes 1 for a stored
// 1; the formula above is the revived form and the stored value is never rewritten.
//
// Derivation + gate (validated signature, never a build hash/RVA: fail CLOSED):
//   - audited evidence: driver_vrlink.dll 13,908,632 B, sha256
//     1e846be041039798580a91452371f6288c614fb4c152126b137e2c693fb77eef
//     (2026-10-17; kept as evidence only, not as a gate);
//   - SteamVR 2.18.4 (13,928,600 B, sha256 8e7100b6...) moved the same code:
//     impl 0xA51D80 -> 0xA577C0, worker 0xA50530 -> 0xA55F70. The prologues and
//     the thunk->worker rel32 relationship were byte-identical; only the RVAs
//     and the caller count (32 -> 36) changed. That is why the gate is now a
//     signature, not an identity check;
//   - call convention re-derived from 32 audited impl call sites: x64 fastcall,
//     rcx = value-transport `this` (owner chain [[obj+0x950]+0x388]+0xa50),
//     edx = u32 ValueTransportID, r8 = const void* payload, r9d = u32 size,
//     5th stack arg = u8 flag class (every audited fixed-size publish, incl.
//     the id-11 width publish, passes 0; the impl doubles it before tail-jump);
//   - worker guards: id <= 0x74 (0x48 = 72 valid), size <= 0x800000, payload
//     delivered into the holder slot [this + id*16 + 0x13e8];
//   - locator: one 12-byte thunk prefix, its rel32 target, one 16-byte worker
//     prologue, and the worker's id/size guards. Exactly one candidate is
//     required; ambiguity refuses (VrlinkSignature.h);
//   - gate JSON + disasm excerpt: ../builds/GalaxyXR-Driver/build/asw/
//     (vrlinktap-gate.json / disasm files, regenerated by build_vrlinktap_gate.py);
//   - channel + unused-id analysis: builds/steamlink-patches/ tree
//     asw-20261017/impl/receipts/06-bridge/REPORT.md §2/§3/§4 (rank 1).
//
// Safety contract (mirrors NvencTap — worst case stock stream + one log line):
//   1. fail CLOSED before anything is hooked or published: the module's own
//      IMAGE_DOS_HEADER / IMAGE_NT_HEADERS must parse (a bad DOS or NT
//      signature is a rejected image), the executable section must be readable
//      and inside SizeOfImage, and the signature resolver must find exactly one
//      thunk/worker pair with the expected id/size guards. Any failure: no
//      hook, no publish, one reason line, observe-only.
//   2. publication happens on the hot-reload SetConfig path (the single
//      control path: GUI toggle/mode -> settings.json -> SetConfig) AND on
//      vrlink's own publish cadence (a pending publish retries on the next
//      captured Valve publish), AND immediately on a NEW transport instance
//      (vrserver restart / reconnect resets the delivered-value latch and
//      re-publishes), never inside per-frame processing, never on a timer.
//      Every path calls PublishDesired(), which re-derives the wanted value
//      from the CURRENT stored state under stateLock, so a pending enable can
//      never overwrite a later explicit Off.
//   3. driver_vrlink.dll is resolved with GetModuleHandleA only (never
//      LoadLibrary); an absent module stays retryable (throttled log, no
//      permanent latch) so a lazily loaded vrlink can still be picked up.
//   4. independent of NvencTap (separate module, separate failure domain);
//      with spacewarp disabled there are no hooks and no behavior changes.
//   5. the explicit user OFF is a legitimate publish (the user's own previous
//      state, published 0 once), never a silent rewrite.
//   6. stateLock guards enabled / mode / publishedValue / havePublished and is
//      held across every read and write in the publish path, including the
//      native call, so a concurrent SetConfig is never torn by a provider tick.
// ============================================================================

// Locator constants. There is deliberately no build hash and no fixed RVA here:
// the resolver (VrlinkSignature.h) finds the thunk/worker structurally, so a
// SteamVR update that only moves the code does not disable the tap. The
// audited values are evidence for the gate artifact, not a runtime gate.
namespace VrlinkTapPin {
	// carrier id (06-bridge §3 sweep: 0 hits on both ends for the candidates;
	// brief 11 pins 0x48; margin under the worker's 0x74 guard)
	constexpr unsigned int kSpacewarpValueTransportId = 0x48;
	// u32 1/0 — the same 4-byte payload class as vrlink's id-11 width publish
	constexpr unsigned int kPublishPayloadBytes = 4;
	// the thunk's 5th (stack byte) argument: fixed-size payload class; every
	// audited fixed-size publish passes 0
	constexpr unsigned char kPublishFlagClass = 0;
	// audited evidence only (2026-10-17 build / 2026-10-25 installed build)
	constexpr uint32_t kAuditedImplRva = 0xA51D80;
	constexpr uint32_t kAuditedWorkerRva = 0xA50530;
	constexpr uint32_t kInstalledImplRva = 0xA577C0;
	constexpr uint32_t kInstalledWorkerRva = 0xA55F70;
}

// Published shape: status is EXACTLY one of "off"/"on"/"waiting"
// (off: disabled; on: enabled and the value was published; waiting: enabled
// but the publish has not happened yet). The Companion (W2c) reads these keys
// and this enum verbatim — the pinned cross-child seam, do not deviate.
// reason / implRva / workerRva / callerCount / moduleImageSize /
// moduleTimestamp are additive diagnostics; older Companions ignore them.
struct VrlinkTapRuntimeState {
	bool enabled = false;
	bool hookInstalled = false;
	bool published = false;      // havePublished && publishedValue != 0
	uint32_t publishedValue = 0; // last value actually delivered on 0x48
	const char* status = "off";
	const char* reason = "off";
	uint32_t implRva = 0;        // resolved thunk RVA (0 before resolution)
	uint32_t workerRva = 0;      // resolved worker RVA
	uint32_t callerCount = 0;    // diagnostic; 32 -> 36 in the 2026-10-25 build
	uint32_t moduleImageSize = 0;
	uint32_t moduleTimestamp = 0;
};

class VrlinkTap{
public:
	static VrlinkTap& Get();

	// single control path: hot reload only (FrameProcessor::UpdateEncoderSettings,
	// beside the NvencTap::SetConfig line). Stores (enabled, mode) under
	// stateLock, resolves+installs the hook when enabled, then publishes the
	// CURRENT desired value: mode 1 -> 2, any other mode -> 1, disabled -> 0.
	// A publish that cannot happen (unresolved signature, no capture, faulted
	// call) leaves status "waiting" and is retried on the next SetConfig or the
	// next captured Valve publish. false publishes 0 only when a value was
	// actually delivered (explicit user off — a legitimate publish of the user's
	// own previous state), then status "off".
	void SetConfig(bool enabled, int mode);
	// compatibility forwarder for a caller that only carries the legacy boolean:
	// same as SetConfig(enabled, 0), the default mode, i.e. carrier 0x48=1.
	void SetConfig(bool enabled);
	VrlinkTapRuntimeState GetRuntimeState();
	// pure tri-state classifier for the pinned seam enum
	static const char* StatusString(bool enabled, bool published);

private:
	VrlinkTap() = default;
	VrlinkTap(const VrlinkTap&) = delete;
	VrlinkTap& operator=(const VrlinkTap&) = delete;

	// idempotent, self-throttled (1/s); called from SetConfig only while enabled
	void TryInstall();
	// recomputes the wanted carrier value from the CURRENT enabled/mode pair and
	// publishes it; caller must NOT hold stateLock (it takes the lock itself and
	// holds it across the native call)
	void PublishDesired();
	void OnVrlinkPublish(void* vts);

	std::mutex stateLock;
	std::mutex installationLock;
	bool enabled = false;         // guarded by stateLock
	int mode = 0;                 // guarded by stateLock: stored spacewarpMode (0 -> carrier 1; 1 -> carrier 2 only while !kHalfRateRetired, else 1)
	uint32_t publishedValue = 0;  // guarded by stateLock: last value actually delivered
	bool havePublished = false;   // guarded by stateLock: a value was delivered at least once
	// newest capture wins (vrlink may replace the value-transport object per
	// session; a fresh publish re-teaches it)
	std::atomic<void*> capturedVts{nullptr};
	std::atomic<bool> installed{false};
	std::atomic<bool> failedPermanently{false};
	double lastAttempt = 0;
	const char* lastReason = "off"; // guarded by stateLock: additive diagnostics
	uint32_t resolvedImplRva = 0;   // guarded by stateLock
	uint32_t resolvedWorkerRva = 0; // guarded by stateLock
	uint32_t resolvedCallerCount = 0;
	uint32_t moduleImageSize = 0;
	uint32_t moduleTimestamp = 0;
	bool loggedModuleAbsent = false; // one-shot: module not loaded yet (retryable)
	bool loggedWaiting = false;      // one-shot latch: signature invalid / unreachable publisher
	bool loggedNoCapture = false;    // one-shot latch: enabled but no vrlink publish seen yet

	friend struct VrlinkTapShims;
};